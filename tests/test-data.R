source('R/data.R',encoding='UTF-8')
source('R/content.R',encoding='UTF-8')
source('R/views.R',encoding='UTF-8')
checks <- 0L
check <- function(x,label) { stopifnot(isTRUE(x)); checks <<- checks+1L; cat('PASS:',label,'\n') }
fails <- function(expr) inherits(tryCatch(force(expr),error=identity),'error')
b <- demo_data(); now <- max(b$observations$time)
check(nrow(b$observations)==2304,'48 hours x 8 stations x 6 metrics')
check(identical(b$observations,demo_data()$observations),'Demo is reproducible')
check(nrow(validate_observations(b$observations,now))==2304,'Demo obeys observation contract')
d <- data.frame(ESTACION='28079004',MAGNITUD='83',ANO='2026',MES='07',DIA='20',
  H01='28,4',V01='V',H02='-2',V02='V',H03='99',V03='N',H24='30',V24='V')
p <- parse_observations(d,'weather',now)
check(nrow(p)==3,'Invalid flagged hours are excluded')
check(p$value[1]==28.4 && p$value[2]== -2,'Decimal commas and sub-zero temperature')
check(all(p$station=='4'),'Full municipality station IDs are normalized')
check(format(p$time[3],'%Y-%m-%d %H:%M',tz='Europe/Madrid')=='2026-07-21 00:00','H24 rolls over to following local midnight')
check(nrow(parse_observations(d,'weather',p$time[1]))==1,'Future observations excluded')
check(fails(parse_observations(d,'air',now)),'Network mismatches are rejected')
bad <- d; bad$MAGNITUD <- '9'; bad$H01 <- '-2'; bad$H02 <- '-3'; bad$H24 <- '-4'
check(fails(parse_observations(bad,'air',now)),'Negative pollution is rejected')
bad <- d; bad$ANO <- '2026'; bad$MES <- '10'; bad$DIA <- '25'
check(fails(parse_observations(bad,'weather',as.POSIXct('2026-11-11',tz='Europe/Madrid'))),'Ambiguous DST transition day rejected')
check(nrow(validate_observations(rbind(p,p),now))==nrow(p),'Duplicate observations removed')
latest <- latest_readings(b$observations,'temperature',now)
check(nrow(latest)==8 && all(latest$fresh),'One latest reading per station')
stale <- latest_readings(b$observations,'temperature',now+4*3600)
check(!any(stale$fresh),'Readings older than 3h are stale')
metadata <- data.frame(CODIGO='28079004',ESTACION='Plaza de España',LATITUD='40,4239',LONGITUD='-3,7123')
st <- parse_stations(metadata,'air')
check(st$station=='4' && st$lat==40.4239,'Official station metadata normalized')
metadata$LATITUD <- '4478000'
check(fails(parse_stations(metadata,'air')),'UTM coordinates never interpreted as latitude')
check(length(unique(paste(b$stations$network,b$stations$station)))==16,'Networks keep independent station identifiers')
map <- as.character(station_map(latest,b$stations,'4',35,'°C'))
check(grepl('data-station="4"',map,fixed=TRUE),'Map has keyboard-selectable station targets')
check(grepl('Sin coordenadas verificadas',as.character(station_map(latest,b$stations[FALSE,],'4',35,'°C')),fixed=TRUE),'No synthetic coordinates used as fallback')
chart <- as.character(trend_chart(b$observations[b$observations$metric=='temperature' & b$observations$station=='4',],35,'°C'))
check(grepl('<polyline',chart,fixed=TRUE),'Trend SVG generated from observations')
gaps <- p[c(1,3),]; chart <- as.character(trend_chart(gaps,35,'°C'))
check(lengths(regmatches(chart,gregexpr('<polyline',chart,fixed=TRUE)))==2,'Outages remain visible as chart gaps')
tmp <- tempfile(fileext='.csv')
writeLines(c('ESTACION;MAGNITUD;ANO;MES;DIA;H01;V01','28079004;83;2026;07;20;28,4;V'),tmp,useBytes=TRUE)
check(nrow(parse_observations(read_public_csv(tmp),'weather',now))==1,'CSV delimiter and data parsing end to end')
writeLines('<!doctype html><html>error</html>',tmp)
check(fails(read_public_csv(tmp)),'HTML error pages rejected as data'); unlink(tmp)
invisible(lapply(c('app.R','setup.R','run.R','preview.R'),function(path) parse(path,encoding='UTF-8')))
check(TRUE,'All R entry points parse')
cat('\n',checks,'checks passed.\n')
